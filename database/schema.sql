-- CA_LAM_VIEC
CREATE TABLE dbo.CA_LAM_VIEC (
    MACA INT IDENTITY(1,1) NOT NULL,
    SOCA INT NOT NULL,
    TGMO TIME(7) NULL,
    TGDONG TIME(7) NULL,
    NGAYLAM DATETIME NOT NULL,
    TMDAUCA DECIMAL(15, 2) NULL,
    TMCUOICA DECIMAL(15, 2) NULL,
    CONSTRAINT PK_CA_LAM_VIEC PRIMARY KEY (MACA),
    CONSTRAINT UQ_CA_NGAY_SOCA UNIQUE (NGAYLAM, SOCA),
    CONSTRAINT CK_CA_LAM_VIEC_KHUNG_GIO_HOP_LE CHECK (TGMO < TGDONG),
    CONSTRAINT CK_CA_LAM_VIEC_SOCA_DUONG CHECK (SOCA > 0),
    CONSTRAINT CK_CA_LAM_VIEC_TIEN_CUOICA_KHONG_AM CHECK (TMCUOICA >= 0),
    CONSTRAINT CK_CA_LAM_VIEC_TIEN_DAUCA_KHONG_AM CHECK (TMDAUCA >= 0)
);
GO

